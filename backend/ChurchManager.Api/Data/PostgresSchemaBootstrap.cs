using Microsoft.EntityFrameworkCore;

namespace ChurchManager.Api.Data;

/// <summary>
/// Additively aligns the existing Render PostgreSQL database with the original
/// English EF table names while adding fields required by the current application.
/// Existing tables and rows are never dropped or renamed.
/// </summary>
public static class PostgresSchemaBootstrap
{
    public static Task EnsureAsync(AppDbContext db, CancellationToken cancellationToken = default)
        => db.Database.ExecuteSqlRawAsync(SchemaSql, cancellationToken);

    private const string SchemaSql = """
        CREATE TABLE IF NOT EXISTS "Churches" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "Name" text NOT NULL,
            "Email" varchar(254) NOT NULL,
            "Phone" text NOT NULL DEFAULT '',
            "Address" text NOT NULL DEFAULT '',
            "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
        );

        CREATE TABLE IF NOT EXISTS "Roles" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "ChurchId" integer NOT NULL,
            "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
            "Name" text NOT NULL,
            "Description" text NOT NULL DEFAULT '',
            "PermissionsJson" text NOT NULL DEFAULT '[]',
            "Users" integer NOT NULL DEFAULT 0
        );

        CREATE TABLE IF NOT EXISTS "Users" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "ChurchId" integer NOT NULL,
            "Name" text NOT NULL,
            "Email" varchar(254) NOT NULL,
            "PasswordHash" varchar(512) NOT NULL,
            "Role" text NOT NULL DEFAULT 'Membro',
            "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
            "CargoId" integer NOT NULL DEFAULT 0,
            "IsActive" boolean NOT NULL DEFAULT TRUE
        );

        CREATE TABLE IF NOT EXISTS "Members" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "ChurchId" integer NOT NULL,
            "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
            "Name" text NOT NULL,
            "Email" text NOT NULL DEFAULT '',
            "Phone" text NOT NULL DEFAULT '',
            "Ministry" text NOT NULL DEFAULT '',
            "Status" text NOT NULL DEFAULT 'Ativo',
            "Role" text NOT NULL DEFAULT 'Membro'
        );

        CREATE TABLE IF NOT EXISTS "Ministries" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "ChurchId" integer NOT NULL,
            "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
            "Name" text NOT NULL,
            "Description" text NOT NULL DEFAULT '',
            "Coordinator" text NOT NULL DEFAULT '',
            "Status" text NOT NULL DEFAULT 'Ativo'
        );

        CREATE TABLE IF NOT EXISTS "Events" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "ChurchId" integer NOT NULL,
            "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
            "Title" text NOT NULL,
            "Description" text NOT NULL DEFAULT '',
            "StartsAt" timestamp with time zone NOT NULL,
            "Location" text NOT NULL DEFAULT '',
            "Ministry" text NOT NULL DEFAULT 'Todos',
            "Status" text NOT NULL DEFAULT 'Planejado',
            "IsRestricted" boolean NOT NULL DEFAULT FALSE,
            "RecurrenceType" varchar(50) NOT NULL DEFAULT 'Nenhuma'
        );

        CREATE TABLE IF NOT EXISTS "Transactions" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "ChurchId" integer NOT NULL,
            "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
            "Description" text NOT NULL,
            "Category" text NOT NULL DEFAULT 'Outros',
            "Amount" numeric(12,2) NOT NULL,
            "TransactionType" text NOT NULL DEFAULT 'Income',
            "TransactionDate" timestamp with time zone NOT NULL,
            "Method" text NOT NULL DEFAULT 'PIX'
        );

        CREATE TABLE IF NOT EXISTS "Scales" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "ChurchId" integer NOT NULL,
            "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
            "Title" text NOT NULL,
            "Ministry" text NOT NULL,
            "StartsAt" timestamp with time zone NOT NULL,
            "AssignedMembersJson" text NOT NULL DEFAULT '[]',
            "Status" text NOT NULL DEFAULT 'Pendente',
            "EventId" integer NULL,
            "LegacyMinistryName" varchar(100) NOT NULL DEFAULT ''
        );

        ALTER TABLE IF EXISTS "Users"
            ADD COLUMN IF NOT EXISTS "CargoId" integer NOT NULL DEFAULT 0;
        ALTER TABLE IF EXISTS "Users"
            ADD COLUMN IF NOT EXISTS "IsActive" boolean NOT NULL DEFAULT TRUE;
        ALTER TABLE IF EXISTS "Events"
            ADD COLUMN IF NOT EXISTS "IsRestricted" boolean NOT NULL DEFAULT FALSE;
        ALTER TABLE IF EXISTS "Events"
            ADD COLUMN IF NOT EXISTS "RecurrenceType" varchar(50) NOT NULL DEFAULT 'Nenhuma';
        ALTER TABLE IF EXISTS "Scales"
            ADD COLUMN IF NOT EXISTS "EventId" integer NULL;
        ALTER TABLE IF EXISTS "Scales"
            ADD COLUMN IF NOT EXISTS "LegacyMinistryName" varchar(100) NOT NULL DEFAULT '';

        CREATE INDEX IF NOT EXISTS "IX_Churches_Email" ON "Churches" ("Email");
        CREATE INDEX IF NOT EXISTS "IX_Members_ChurchId" ON "Members" ("ChurchId");
        CREATE INDEX IF NOT EXISTS "IX_Ministries_ChurchId" ON "Ministries" ("ChurchId");
        CREATE INDEX IF NOT EXISTS "IX_Events_ChurchId" ON "Events" ("ChurchId");
        CREATE INDEX IF NOT EXISTS "IX_Transactions_ChurchId" ON "Transactions" ("ChurchId");
        CREATE INDEX IF NOT EXISTS "IX_Roles_ChurchId" ON "Roles" ("ChurchId");
        CREATE INDEX IF NOT EXISTS "IX_Scales_ChurchId" ON "Scales" ("ChurchId");
        """;
}
