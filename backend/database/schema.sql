CREATE DATABASE IF NOT EXISTS churchmanager CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE churchmanager;

CREATE TABLE IF NOT EXISTS Churches (
  Id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  Name VARCHAR(180) NOT NULL,
  Email VARCHAR(254) NOT NULL,
  Phone VARCHAR(40) NOT NULL DEFAULT '',
  Address VARCHAR(250) NOT NULL DEFAULT '',
  CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  INDEX IX_Churches_Email (Email)
);
CREATE TABLE IF NOT EXISTS Users (
  Id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  ChurchId INT NOT NULL,
  Name VARCHAR(160) NOT NULL,
  Email VARCHAR(254) NOT NULL,
  PasswordHash VARCHAR(512) NOT NULL,
  Role VARCHAR(80) NOT NULL DEFAULT 'Membro',
  CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  UNIQUE KEY IX_Users_Email (Email),
  CONSTRAINT FK_Users_Churches FOREIGN KEY (ChurchId) REFERENCES Churches(Id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS Members (
  Id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, ChurchId INT NOT NULL,
  Name VARCHAR(160) NOT NULL, Email VARCHAR(254) NOT NULL DEFAULT '', Phone VARCHAR(40) NOT NULL DEFAULT '',
  Ministry VARCHAR(120) NOT NULL DEFAULT '', Status VARCHAR(40) NOT NULL DEFAULT 'Ativo', Role VARCHAR(80) NOT NULL DEFAULT 'Membro',
  CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), INDEX IX_Members_ChurchId (ChurchId),
  CONSTRAINT FK_Members_Churches FOREIGN KEY (ChurchId) REFERENCES Churches(Id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS Ministries (
  Id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, ChurchId INT NOT NULL, Name VARCHAR(160) NOT NULL,
  Description VARCHAR(500) NOT NULL DEFAULT '', Coordinator VARCHAR(160) NOT NULL DEFAULT '', Status VARCHAR(40) NOT NULL DEFAULT 'Ativo',
  CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), INDEX IX_Ministries_ChurchId (ChurchId),
  CONSTRAINT FK_Ministries_Churches FOREIGN KEY (ChurchId) REFERENCES Churches(Id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS Events (
  Id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, ChurchId INT NOT NULL, Title VARCHAR(180) NOT NULL,
  Description VARCHAR(1000) NOT NULL DEFAULT '', StartsAt DATETIME(6) NOT NULL, Location VARCHAR(180) NOT NULL DEFAULT '',
  Ministry VARCHAR(120) NOT NULL DEFAULT 'Todos', Status VARCHAR(40) NOT NULL DEFAULT 'Planejado',
  CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), INDEX IX_Events_ChurchId (ChurchId),
  INDEX IX_Events_ChurchId_StartsAt (ChurchId, StartsAt),
  CONSTRAINT FK_Events_Churches FOREIGN KEY (ChurchId) REFERENCES Churches(Id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS Transactions (
  Id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, ChurchId INT NOT NULL, Description VARCHAR(180) NOT NULL,
  Category VARCHAR(100) NOT NULL DEFAULT 'Outros', Amount DECIMAL(12,2) NOT NULL,
  TransactionType VARCHAR(30) NOT NULL DEFAULT 'Income', TransactionDate DATETIME(6) NOT NULL,
  Method VARCHAR(50) NOT NULL DEFAULT 'PIX', CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  INDEX IX_Transactions_ChurchId (ChurchId), INDEX IX_Transactions_ChurchId_TransactionDate (ChurchId, TransactionDate),
  CONSTRAINT FK_Transactions_Churches FOREIGN KEY (ChurchId) REFERENCES Churches(Id) ON DELETE CASCADE,
  CONSTRAINT CK_Transactions_Amount CHECK (Amount > 0), CONSTRAINT CK_Transactions_Type CHECK (TransactionType IN ('Income','Expense'))
);
CREATE TABLE IF NOT EXISTS Roles (
  Id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, ChurchId INT NOT NULL, Name VARCHAR(120) NOT NULL,
  Description VARCHAR(500) NOT NULL DEFAULT '', PermissionsJson JSON NOT NULL, Users INT NOT NULL DEFAULT 0,
  CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), INDEX IX_Roles_ChurchId (ChurchId),
  CONSTRAINT FK_Roles_Churches FOREIGN KEY (ChurchId) REFERENCES Churches(Id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS Scales (
  Id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, ChurchId INT NOT NULL, Title VARCHAR(180) NOT NULL,
  Ministry VARCHAR(120) NOT NULL DEFAULT '', StartsAt DATETIME(6) NOT NULL, AssignedMembersJson JSON NOT NULL,
  Status VARCHAR(40) NOT NULL DEFAULT 'Pendente', CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  INDEX IX_Scales_ChurchId (ChurchId), INDEX IX_Scales_ChurchId_StartsAt (ChurchId, StartsAt),
  CONSTRAINT FK_Scales_Churches FOREIGN KEY (ChurchId) REFERENCES Churches(Id) ON DELETE CASCADE
);